    public static bool IsDataType(string name)
    {
        var upper = name.ToUpperInvariant();
        var isDataType = DataTypes.Contains(upper);
        return isDataType;
    }

    public static bool Contains(string name)
    {
        var upper = name.ToUpperInvariant();
        var isKnown = Keywords.Contains(upper) || BuiltInFunctions.Contains(upper);
        return isKnown;
    }

    public static bool IsBuiltInFunction(string name)
    {
        var upper = name.ToUpperInvariant();
        var isBuiltIn = BuiltInFunctions.Contains(upper);
        return isBuiltIn;
    }
